#!/usr/bin/env python3
"""
Консольный скрипт для замера скорости скачивания.

Делает N последовательных запросов к указанному адресу, полностью скачивает
каждый ответ, а затем печатает среднее время запроса, общий объём данных
и скорость скачивания в Мбит/с.
"""

# argparse - стандартный модуль для разбора аргументов командной строки
import argparse
# sys нужен, чтобы выходить из программы с кодом ошибки (sys.exit)
import sys
# time.perf_counter - самый точный таймер для измерения коротких интервалов
import time
# urllib.request - встроенный HTTP-клиент (чтобы не ставить библиотеку requests)
import urllib.request
# URLError и HTTPError - типы ошибок сети и ошибок вроде 404/500
from urllib.error import HTTPError, URLError

# Сколько запросов делаем (по условию задания - 10)
REQUESTS_COUNT = 10
# Размер "порции", которую читаем из сети за раз: 64 КБ.
# Читаем кусками, чтобы не загружать весь файл в память сразу.
CHUNK_SIZE = 64 * 1024
# Сколько секунд ждём ответ сервера, прежде чем считать запрос зависшим
TIMEOUT_SECONDS = 30


def download_once(url):
    """
    Делает ОДИН запрос и дожидается полного скачивания ответа.
    Возвращает кортеж: (сколько байт скачали, сколько секунд это заняло).
    """
    # Некоторые сервера отклоняют запросы без User-Agent, поэтому задаём его вручную
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "speedtest-script/1.0"}
    )

    # Счётчик скачанных байт для этого запроса
    total_bytes = 0

    # Засекаем время ПЕРЕД отправкой запроса
    start = time.perf_counter()

    # Отправляем запрос; "with" гарантирует, что соединение закроется само
    with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
        # Крутим цикл, пока сервер не отдаст всё тело ответа
        while True:
            # Читаем следующий кусок данных (до 64 КБ)
            chunk = response.read(CHUNK_SIZE)
            # Пустой кусок значит, что данные закончились - выходим из цикла
            if not chunk:
                break
            # Прибавляем размер куска к счётчику байт
            total_bytes += len(chunk)

    # Засекаем время ПОСЛЕ того, как всё скачано, и считаем разницу
    elapsed = time.perf_counter() - start

    return total_bytes, elapsed


def main():
    # Описываем, какие аргументы принимает скрипт
    parser = argparse.ArgumentParser(description="Замер скорости скачивания по URL")
    # Единственный обязательный аргумент - адрес, к которому стучимся
    parser.add_argument("url", help="адрес файла, например тяжёлой картинки")
    # Разбираем то, что пользователь передал в командной строке
    args = parser.parse_args()

    # Сюда будем складывать время каждого запроса (в секундах)
    durations = []
    # Сюда - общий объём скачанных данных за все запросы (в байтах)
    total_bytes = 0

    print(f"Адрес: {args.url}")
    print(f"Делаем {REQUESTS_COUNT} запросов последовательно...\n")

    # Цикл ровно из 10 итераций; запросы идут строго один за другим,
    # потому что следующий начинается только после завершения предыдущего
    for i in range(1, REQUESTS_COUNT + 1):
        try:
            # Выполняем один запрос и получаем (байты, секунды)
            size, elapsed = download_once(args.url)
        except HTTPError as e:
            # Сервер ответил ошибкой (404, 500 и т.п.)
            print(f"Ошибка HTTP {e.code} на запросе №{i}", file=sys.stderr)
            sys.exit(1)
        except (URLError, TimeoutError) as e:
            # Нет сети, неверный адрес или сервер не ответил вовремя
            print(f"Ошибка сети на запросе №{i}: {e}", file=sys.stderr)
            sys.exit(1)

        # Запоминаем время этого запроса
        durations.append(elapsed)
        # Добавляем скачанные байты к общему итогу
        total_bytes += size

        # Печатаем прогресс: размер переводим из байт в мегабайты (1 МБ = 1 000 000 байт)
        print(f"Запрос {i:>2}: {size / 1_000_000:.2f} МБ за {elapsed:.3f} с")

    # Общее время всех запросов - сумма времён каждого
    total_time = sum(durations)
    # Среднее время запроса = общее время / количество запросов
    avg_time = total_time / REQUESTS_COUNT
    # Скорость = всего бит / всего секунд. Умножаем байты на 8, чтобы получить биты,
    # и делим на 1 000 000, чтобы получить мегабиты (Мбит/с)
    speed_mbit = (total_bytes * 8) / total_time / 1_000_000
    # Та же скорость, но в мегабайтах в секунду (МБ/с) - для наглядности
    speed_mbyte = total_bytes / total_time / 1_000_000

    # Выводим итоговые результаты
    print("\n--- Результаты ---")
    print(f"Среднее время запроса:  {avg_time:.3f} с")
    print(f"Всего скачано:          {total_bytes / 1_000_000:.2f} МБ")
    print(f"Скорость скачивания:    {speed_mbit:.2f} Мбит/с ({speed_mbyte:.2f} МБ/с)")


# Эта проверка означает: запускать main() только если файл запущен напрямую,
# а не импортирован как модуль в другой скрипт
if __name__ == "__main__":
    main()